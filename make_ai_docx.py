from docx import Document
from docx.shared import Pt, RGBColor, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

doc = Document()

for section in doc.sections:
    section.top_margin    = Cm(1.2)
    section.bottom_margin = Cm(1.2)
    section.left_margin   = Cm(1.3)
    section.right_margin  = Cm(1.3)

    sectPr = section._sectPr
    cols = OxmlElement("w:cols")
    cols.set(qn("w:num"), "2")
    cols.set(qn("w:space"), "425")
    sectPr.append(cols)

RED  = RGBColor(0xDC, 0x26, 0x26)
DARK = RGBColor(0x0F, 0x17, 0x2A)

def header(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(7)
    p.paragraph_format.space_after  = Pt(2)
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(8)
    r.font.color.rgb = RED
    r.font.name = "Calibri"
    rPr = r._r.get_or_add_rPr()
    sp = OxmlElement("w:spacing"); sp.set(qn("w:val"), "60"); rPr.append(sp)

def line(doc, text, bold=False):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after  = Pt(3)
    r = p.add_run(text)
    r.bold = bold
    r.font.size = Pt(10)
    r.font.color.rgb = DARK
    r.font.name = "Calibri"

def divider(doc):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.space_after  = Pt(0)
    pPr = p._p.get_or_add_pPr()
    pBdr = OxmlElement("w:pBdr")
    bot = OxmlElement("w:bottom")
    bot.set(qn("w:val"), "single"); bot.set(qn("w:sz"), "2")
    bot.set(qn("w:space"), "1");    bot.set(qn("w:color"), "CBD5E1")
    pBdr.append(bot); pPr.append(pBdr)

# ── Заголовок ──────────────────────────────────────────────────────────────
p = doc.add_paragraph()
p.alignment = WD_ALIGN_PARAGRAPH.CENTER
p.paragraph_format.space_after = Pt(4)
r = p.add_run("Речь · Модуль интеллектуальной проверки · Gradus")
r.bold = True; r.font.size = Pt(11); r.font.color.rgb = RED; r.font.name = "Calibri"

divider(doc)

# ── ВСТУПЛЕНИЕ ────────────────────────────────────────────────────────────
header(doc, "ВСТУПЛЕНИЕ")
line(doc, "Здравствуйте, уважаемые члены комиссии.")
line(doc, "В рамках нашего дипломного проекта я отвечал за разработку модуля интеллектуальной проверки.")
line(doc, "И сегодня я бы хотел рассказать, какую задачу этот модуль решает, как он устроен, и самое главное, какие инженерные решения я в него заложил.")

divider(doc)

# ── ПРОБЛЕМА ──────────────────────────────────────────────────────────────
header(doc, "ПРОБЛЕМА")
line(doc, "Итак, начнем с проблемы. Дело в том, что обычные платформы проверяют код автоматическими тестами – то есть просто сравнивают результат программы с эталоном.")
line(doc, "Но у такого подхода есть серьезные ограничения: тест видит результат, но совершенно не видит, как написан код.")
line(doc, "Иными словами, студент может сдать рабочее, но при этом не эффективное или небрежное решение – а тест все равно его зачтет.")
line(doc, "Вот именно поэтому и понадобился инструмент, который оценивает не то, работает ли код, а то, насколько хорошо он написан.")
line(doc, "И как раз эту задачу решает мой модуль.")

divider(doc)

# ── ПРЕЗЕНТАЦИЯ ───────────────────────────────────────────────────────────
header(doc, "ДВА РЕЖИМА РАБОТЫ (СЛАЙД)")
line(doc, "Сейчас на слайде вы видите два реальных примера его работы.")
line(doc, "Слева – отдельный режим код ревью: здесь система выставляет оценку по трем показателям – качество, логика и стиль, каждый до ста процентов, и разбирает ошибки прямо по строкам.")
line(doc, "А справа – работа AI наставника, внутри курса: тут он процентов не ставит, а объясняет словами, что в решении хорошо и что стоит улучшить, и даже предлагает исправленный код.")

divider(doc)

# ── ВНУТРЯНКА ─────────────────────────────────────────────────────────────
header(doc, "КАК ЭТО УСТРОЕНО ВНУТРИ")
line(doc, "Теперь перейду к тому, как это устроено внутри. Сам анализ выполняет нейросеть через API.")
line(doc, "Однако, и это важно подчеркнуть, основная инженерная работа здесь – не в самой нейросети, а в системе, которую я выстроил вокруг неё.")
line(doc, "И тут я бы выделил 3 ключевых решения.")

divider(doc)

# ── РЕШЕНИЕ 1 ─────────────────────────────────────────────────────────────
header(doc, "РЕШЕНИЕ 1 — ОТКАЗОУСТОЙЧИВОСТЬ")
line(doc, "Во-первых, это отказоустойчивость. Я специально сделал так, чтобы система не зависела от одного сервиса.")
line(doc, "Если основная нейросеть вдруг недоступна или превышения лимит запросов, система автоматически переключается на резервную.")
line(doc, "Таким образом, чтобы не случилось, студент все равно получит ответ, а не ошибку.")

divider(doc)

# ── РЕШЕНИЕ 2 ─────────────────────────────────────────────────────────────
header(doc, "РЕШЕНИЕ 2 — КЭШИРОВАНИЕ (КЛЮЧЕВОЕ)")
line(doc, "Во-вторых, это, пожалуй, ключевое – система кэширования. Смысл в том, что обращения к нейросети платные и довольно медленные, поэтому повторные запросы нужно отсекать.")
line(doc, "Для этого каждый фрагмент кода я превращаю в уникальный отпечаток – по алгоритму хэширования SHA-256.")
line(doc, "Если точно такой же код уже проверялся раньше, система мгновенно отдает готовый результат из памяти, вообще не обращаясь к нейросети.")
line(doc, "Эффект здесь вполне ощутимый: повторная проверка вместо полутора секунд занимает всего лишь 6 тысячных секунд – это ускорение в 266 раз. А главное – такие запросы не стоят ничего.")
line(doc, "То есть, при тысячах студентов это дает и скорость, и реальную экономию.")

divider(doc)

# ── РЕШЕНИЕ 3 ─────────────────────────────────────────────────────────────
header(doc, "РЕШЕНИЕ 3 — ОБРАБОТКА НЕНАДЁЖНЫХ ДАННЫХ")
line(doc, "И в-третьих – это обработка ненадежных данных. Дело в том, что нейросеть отвечает обычным текстом, иногда с лишними символами.")
line(doc, "Поэтому её ответ я очищаю от лишнего, проверяю его и привожу к нужному формату, а сами оценки – к единой шкале от нуля до ста.")
line(doc, "Кроме того, все входящие данные проверяются заранее, и всё некорректное отсекается еще до основной проверки.")

divider(doc)

# ── ИТОГИ ─────────────────────────────────────────────────────────────────
header(doc, "ИТОГИ")
line(doc, "Подводя итог. Моя работа – это не просто подключение к готовой нейросети, а целая система вокруг нее: она устойчива к сбоям, экономит за счет кэширования и умеет работать с любыми ответами модели.")
line(doc, "Проще говоря, я превратил обычную нейросеть в надежный рабочий инструмент, который можно встроить в любую учебную платформу.", bold=True)
line(doc, "Благодарю за внимание. Я готов ответить на ваши вопросы.", bold=True)

# ── Сохранить ─────────────────────────────────────────────────────────────
out = r"C:\Users\yaros\Desktop\stepashka\шпаргалка_AI_проверка.docx"
doc.save(out)
print(f"Saved: {out}")
