/**
 * components/ui/Card.tsx — Универсальная карточка-контейнер
 *
 * Простейший layout-компонент: оборачивает любое содержимое в блок
 * с базовым стилем карточки (`card` CSS-класс) и отступами (`p-6`).
 *
 * ──────────────────────────────────────────────────────────────
 * ЗАЧЕМ НУЖЕН ЭТОТ КОМПОНЕНТ
 * ──────────────────────────────────────────────────────────────
 * В приложении повсеместно используются карточки с одинаковым визуальным
 * стилем: фон, рамка, тень, скруглённые углы. Вместо того чтобы каждый раз
 * писать `<div className="card p-6 ...">`, используется этот компонент.
 * Если дизайн карточки изменится — достаточно поправить здесь или в CSS.
 *
 * ──────────────────────────────────────────────────────────────
 * CSS-КЛАСС `card`
 * ──────────────────────────────────────────────────────────────
 * Определён в глобальных стилях (index.css или globals.css).
 * Обычно включает:
 *   - background: var(--surface)        — цвет поверхности (светлый/тёмный)
 *   - border: 1px solid var(--border)   — тонкая рамка под тему
 *   - border-radius: 0.75rem            — скруглённые углы
 *   - box-shadow: ...                   — лёгкая тень для глубины
 *
 * ──────────────────────────────────────────────────────────────
 * ПРОПСЫ
 * ──────────────────────────────────────────────────────────────
 * children   — содержимое карточки (любые React-элементы)
 * className  — дополнительные Tailwind-классы для переопределения стилей
 *              (например, "p-4" чтобы сделать отступ меньше стандартного p-6)
 * style      — инлайн-стили для тонких правок (например, конкретная высота)
 *
 * ──────────────────────────────────────────────────────────────
 * ПРИМЕР ИСПОЛЬЗОВАНИЯ
 * ──────────────────────────────────────────────────────────────
 * // Базовое использование:
 * <Card>
 *   <h2>Заголовок</h2>
 *   <p>Текст внутри карточки</p>
 * </Card>
 *
 * // С дополнительным классом (уменьшаем padding):
 * <Card className="p-3">
 *   <SmallWidget />
 * </Card>
 *
 * // С инлайн-стилем (фиксированная высота для скролла):
 * <Card style={{ maxHeight: 400, overflowY: "auto" }}>
 *   <LongList />
 * </Card>
 */

import type { ReactNode, CSSProperties } from "react";

// Пропсы компонента Card
type Props = {
  children: ReactNode;     // Любое содержимое: текст, компоненты, JSX
  className?: string;      // Необязательный класс для расширения/переопределения стилей
  style?: CSSProperties;   // Необязательный инлайн-стиль для тонкой настройки
};

/**
 * Card — базовая карточка с отступами p-6 и стилем из CSS-класса `card`.
 * Используется во всём приложении как контейнер для блоков контента.
 */
export default function Card({ children, className = "", style }: Props) {
  return (
    // `card` — глобальный CSS-класс (фон, рамка, тень, скругления)
    // `p-6`  — внутренний отступ 24px со всех сторон (Tailwind)
    // className передаётся последним, чтобы внешние классы могли переопределить p-6
    <div className={`card p-6 ${className}`} style={style}>
      {children}
    </div>
  );
}
