from docx import Document
from docx.shared import Pt, RGBColor, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

doc = Document()

for section in doc.sections:
    section.top_margin    = Cm(1.2)
    section.bottom_margin = Cm(1.2)
    section.left_margin   = Cm(1.3)
    section.right_margin  = Cm(1.3)

    # Две колонки
    from docx.oxml import OxmlElement
    sectPr = section._sectPr
    cols = OxmlElement("w:cols")
    cols.set(qn("w:num"), "2")
    cols.set(qn("w:space"), "425")  # ~0.75cm между колонками
    sectPr.append(cols)

RED  = RGBColor(0xDC, 0x26, 0x26)
DARK = RGBColor(0x0F, 0x17, 0x2A)

def header(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(7)
    p.paragraph_format.space_after  = Pt(2)
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(8)
    r.font.color.rgb = RED
    r.font.name = "Calibri"
    rPr = r._r.get_or_add_rPr()
    sp = OxmlElement("w:spacing"); sp.set(qn("w:val"), "60"); rPr.append(sp)

def line(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after  = Pt(2)
    r = p.add_run(text)
    r.font.size = Pt(10)
    r.font.color.rgb = DARK
    r.font.name = "Calibri"

def divider(doc):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(1)
    p.paragraph_format.space_after  = Pt(0)
    pPr = p._p.get_or_add_pPr()
    pBdr = OxmlElement("w:pBdr")
    bot = OxmlElement("w:bottom")
    bot.set(qn("w:val"), "single"); bot.set(qn("w:sz"), "2")
    bot.set(qn("w:space"), "1");    bot.set(qn("w:color"), "CBD5E1")
    pBdr.append(bot); pPr.append(pBdr)

# ── Заголовок ──────────────────────────────────────────────────────────────
p = doc.add_paragraph()
p.alignment = WD_ALIGN_PARAGRAPH.CENTER
p.paragraph_format.space_after = Pt(3)
r = p.add_run("Речь · Модуль заданий и проверок · Gradus")
r.bold = True; r.font.size = Pt(10); r.font.color.rgb = RED; r.font.name = "Calibri"

divider(doc)

# ── ВСТУПЛЕНИЕ ────────────────────────────────────────────────────────────
header(doc, "ВСТУПЛЕНИЕ")
line(doc, "Следующим в реализации проекта стал модуль заданий и проверок.")
line(doc, "После создания курса преподавателем, курс следует наполнить заданиями, то есть шагами.")
line(doc, "Задания могут быть 4 видов: теория, тест, код, эссе (задание с подробным текстовым ответом)")
line(doc, "Разберем каждый вид подробнее.")

divider(doc)

# ── ВИДЫ ЗАДАНИЙ ──────────────────────────────────────────────────────────
header(doc, "ВИДЫ ЗАДАНИЙ")
line(doc, "Задание с теорией - задание, в котором преподаватель заносит теоретический материал урока. Для прохождения такого типа задания ученику достаточно прочитать текст и перейти на следующий шаг.")
line(doc, "Тестовое задание - преподаватель вносит условие задания, а также варианты ответов (минимум два). Среди всех внесенных вариантов преподаватель должен выбрать верный, можно выбрать только один правильный вариант ответа. Чтобы пройти задание такого типа ученику следует выбрать верный вариант ответа.")
line(doc, "Задания с кодом - задания на программирование, самый интересный вид задания в проекте. Преподаватель также заносит условие задания и может выбрать варианты проверки. Их представлено 5 видов: переменная, вызов функции, вывод содержит, строк в выводе, ввод-вывод.")
line(doc, "Разберем каждый вид подробнее.")

divider(doc)

# ── ПРОВЕРКИ ──────────────────────────────────────────────────────────────
header(doc, "ВИДЫ ПРОВЕРОК ДЛЯ КОД-ЗАДАНИЙ")
line(doc, "Проверка переменной - преподаватель вносит одну или несколько обязательных переменных, например name и age. Система прогонит весь код, и если не найдет в нем соответствующих переменных, то задание не засчитается как выполненное. Если же все указанные преподавателем переменные в коде ответа найдены, то шаг засчитывается выполненным.")
line(doc, "Проверка вызова функции - преподаватель указывает имя/имена функции, которые обязательно должны быть вызваны в коде, например print(. Система прогонит код, если функции не вызываются - шаг не выполнен, все функции вызываются - выполнен.")
line(doc, "Проверка содержания вывода - преподаватель вносит текст, который обязательно должен быть в выводе программы. Система запустит код и проверит, содержит ли вывод этот текст. Если вывод содержит строку не полностью или не содержит вовсе - шаг не выполнен, если содержит - выполнен.")
line(doc, "Проверка строк в выводе - преподаватель заносит количество минимальных непустых строк вывода, полезно для заданий на циклы. Система запустит код, и сверит количество строк вывода с минимально допустимым значением. Если меньше - шаг не выполнен, если равно или больше - выполнен.")
line(doc, "Проверка ввод-вывод - полноценный тест-кейс. Преподаватель заносит ввод и ожидаемый от кода вывод. Система запустит код с указанным вводом и сравнит полученный вывод с ожидаемым, например, проверка четности и нечетности числа. Если полученный вывод совпадает с ожидаемым - шаг пройден, иначе - не пройден.")
line(doc, "В одном задании можно комбинировать различные варианты проверок. Если преподаватель не укажет ни одной проверки, ИИ проверит код свободно, например, запускается ли код вообще и корректен ли синтаксис.")

divider(doc)

# ── ЭССЕ ──────────────────────────────────────────────────────────────────
header(doc, "ЗАДАНИЕ-ЭССЕ")
line(doc, "Последний тип задания - задание эссе, с развернутым текстовым ответом. Преподаватель указывает условие задания, например \"Опишите преимущества ООП\", а также указывает набор ключевых слов/фраз, которые обязательно должны присутствовать в тексте ответа, например \"инкапсуляция, наследование, полиморфизм\". Если хотя бы одно из ключевых слов не было использовано - система укажет на него, а шаг не засчитается выполненным. Если в тексте ответа использованы все ключевые слова - шаг выполнен.")
line(doc, "Преподаватель также может не указывать ключевые слова, тогда ИИ проверит эссе в свободной форме.")

divider(doc)

# ── ЗАКЛЮЧЕНИЕ ────────────────────────────────────────────────────────────
header(doc, "ЗАКЛЮЧЕНИЕ")
line(doc, "Таким образом, был разработан модуль заданий и проверок, который полностью реализует необходимый функционал для преподавателей при заполнении курса заданиями, и для учеников, проходящих курсы эти задания.")

# ── Сохранить ─────────────────────────────────────────────────────────────
out = r"C:\Users\yaros\Desktop\stepashka\шпаргалка_задания.docx"
doc.save(out)
print(f"Saved: {out}")
