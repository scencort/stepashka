from docx import Document
from docx.shared import Pt, RGBColor, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

doc = Document()

# ── Поля страницы ──────────────────────────────────────────────────────────
for section in doc.sections:
    section.top_margin    = Cm(2.0)
    section.bottom_margin = Cm(2.0)
    section.left_margin   = Cm(2.5)
    section.right_margin  = Cm(2.5)

# ── Цвета ──────────────────────────────────────────────────────────────────
RED       = RGBColor(0xDC, 0x26, 0x26)
DARK      = RGBColor(0x0F, 0x17, 0x2A)
GRAY      = RGBColor(0x64, 0x74, 0x8B)
LIGHT_BG  = RGBColor(0xF1, 0xF5, 0xF9)

# ── Хелперы ────────────────────────────────────────────────────────────────

def add_title(doc, text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(text)
    run.bold = True
    run.font.size = Pt(20)
    run.font.color.rgb = RED
    run.font.name = "Calibri"
    p.paragraph_format.space_after = Pt(4)
    return p

def add_subtitle(doc, text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(text)
    run.font.size = Pt(11)
    run.font.color.rgb = GRAY
    run.font.name = "Calibri"
    p.paragraph_format.space_after = Pt(18)
    return p

def add_section_header(doc, text):
    """Красный заголовок раздела с горизонтальной линией"""
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(16)
    p.paragraph_format.space_after  = Pt(6)
    run = p.add_run(text.upper())
    run.bold = True
    run.font.size = Pt(9)
    run.font.color.rgb = RED
    run.font.name = "Calibri"
    # letter spacing effect via xml
    rPr = run._r.get_or_add_rPr()
    spacing = OxmlElement("w:spacing")
    spacing.set(qn("w:val"), "80")
    rPr.append(spacing)
    return p

def add_body(doc, text, bold_part=None):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(5)
    p.paragraph_format.left_indent = Cm(0)
    if bold_part and text.startswith(bold_part):
        r1 = p.add_run(bold_part)
        r1.bold = True
        r1.font.size = Pt(11)
        r1.font.color.rgb = DARK
        r1.font.name = "Calibri"
        r2 = p.add_run(text[len(bold_part):])
        r2.font.size = Pt(11)
        r2.font.color.rgb = DARK
        r2.font.name = "Calibri"
    else:
        run = p.add_run(text)
        run.font.size = Pt(11)
        run.font.color.rgb = DARK
        run.font.name = "Calibri"
    return p

def add_note(doc, text):
    """Серая пояснительная строка"""
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(3)
    run = p.add_run(text)
    run.font.size = Pt(10)
    run.font.color.rgb = GRAY
    run.font.name = "Calibri"
    run.italic = True
    return p

def add_divider(doc):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.space_after  = Pt(2)
    pPr = p._p.get_or_add_pPr()
    pBdr = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "single")
    bottom.set(qn("w:sz"),  "4")
    bottom.set(qn("w:space"), "1")
    bottom.set(qn("w:color"), "E2E8F0")
    pBdr.append(bottom)
    pPr.append(pBdr)
    return p

def add_qa_block(doc, question, answer):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(8)
    p.paragraph_format.space_after  = Pt(2)
    run = p.add_run(question)
    run.bold = True
    run.font.size = Pt(11)
    run.font.color.rgb = DARK
    run.font.name = "Calibri"

    p2 = doc.add_paragraph()
    p2.paragraph_format.space_after  = Pt(2)
    p2.paragraph_format.left_indent  = Cm(0.4)
    run2 = p2.add_run(answer)
    run2.font.size = Pt(10.5)
    run2.font.color.rgb = GRAY
    run2.font.name = "Calibri"

