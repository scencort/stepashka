line(doc, "Во время прохождения курса учениками информация о выполненных шагах передаётся в систему отслеживания прогресса, а собранные данные используются аналитическим модулем для формирования статистики и оценки эффективности обучения.")

divider(doc)

# ── ЗАКЛЮЧЕНИЕ ────────────────────────────────────────────────────────────
header(doc, "ЗАКЛЮЧЕНИЕ")
line(doc, "Таким образом, разработанный модуль управления курсами обеспечивает полный цикл работы с образовательным контентом — от создания и настройки курса до его публикации и дальнейшего сопровождения.")
line(doc, "Он выступает центральным элементом всей образовательной платформы, обеспечивая преподавателям удобное управление учебными программами и создавая основу для взаимодействия всех остальных подсистем проекта.", bold=True)

