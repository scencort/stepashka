from docx import Document
from docx.shared import Pt, RGBColor, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

doc = Document()

for section in doc.sections:
    section.top_margin    = Cm(2.0)
    section.bottom_margin = Cm(2.0)
    section.left_margin   = Cm(2.5)
    section.right_margin  = Cm(2.5)

RED  = RGBColor(0xDC, 0x26, 0x26)
DARK = RGBColor(0x0F, 0x17, 0x2A)

def header(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(7)
    p.paragraph_format.space_after  = Pt(2)
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(8)
    r.font.color.rgb = RED
    r.font.name = "Calibri"
    rPr = r._r.get_or_add_rPr()
    sp = OxmlElement("w:spacing"); sp.set(qn("w:val"), "60"); rPr.append(sp)

def line(doc, text, bold=False):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after  = Pt(3)
    r = p.add_run(text)
    r.bold = bold
    r.font.size = Pt(11)
    r.font.color.rgb = DARK
    r.font.name = "Calibri"

def divider(doc):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.space_after  = Pt(0)
    pPr = p._p.get_or_add_pPr()
    pBdr = OxmlElement("w:pBdr")
    bot = OxmlElement("w:bottom")
    bot.set(qn("w:val"), "single"); bot.set(qn("w:sz"), "2")
    bot.set(qn("w:space"), "1");    bot.set(qn("w:color"), "CBD5E1")
    pBdr.append(bot); pPr.append(pBdr)

# ── Заголовок ──────────────────────────────────────────────────────────────
p = doc.add_paragraph()
p.alignment = WD_ALIGN_PARAGRAPH.CENTER
p.paragraph_format.space_after = Pt(4)
r = p.add_run("Речь · Модуль управления курсами · Gradus")
r.bold = True; r.font.size = Pt(11); r.font.color.rgb = RED; r.font.name = "Calibri"

divider(doc)

# ── ВСТУПЛЕНИЕ ────────────────────────────────────────────────────────────
header(doc, "ВСТУПЛЕНИЕ")
line(doc, "Следующим компонентом образовательной платформы стал модуль управления курсами.")
line(doc, "Данный модуль является основой для организации учебного контента и обеспечивает преподавателю полный набор инструментов для создания и сопровождения образовательных программ.")
line(doc, "Именно в рамках этого модуля формируется структура курса, которая в дальнейшем используется всеми остальными подсистемами платформы — модулем заданий и проверок, системой прохождения курсов учениками и модулем аналитики.")

divider(doc)

# ── ПОШАГОВЫЙ МАСТЕР ──────────────────────────────────────────────────────
header(doc, "ПОШАГОВЫЙ МАСТЕР СОЗДАНИЯ КУРСА")
line(doc, "При разработке особое внимание было уделено удобству работы преподавателя.")
line(doc, "Процесс создания курса реализован в виде пошагового мастера, который разделён на несколько последовательных этапов.")
line(doc, "Такой подход позволяет постепенно заполнять информацию о курсе и не перегружает пользователя большим количеством настроек на одном экране.")

divider(doc)

# ── ЭТАП 1 ────────────────────────────────────────────────────────────────
header(doc, "ЭТАП 1 — ОСНОВНАЯ ИНФОРМАЦИЯ")
line(doc, "На первом этапе преподаватель заполняет основную информацию о курсе.")
line(doc, "Здесь указывается название курса, уникальный URL-адрес для доступа к нему, описание, категория, уровень сложности и стоимость.")
line(doc, "Благодаря этому система получает все необходимые данные для отображения курса в каталоге и его дальнейшей идентификации.")
line(doc, "Для преподавателя это удобно тем, что вся ключевая информация находится в одном месте и может быть изменена в любой момент.")

divider(doc)

# ── ЭТАП 2 ────────────────────────────────────────────────────────────────
header(doc, "ЭТАП 2 — СТРУКТУРА КУРСА")
line(doc, "После сохранения основной информации преподаватель переходит к формированию структуры курса.")
line(doc, "Курс состоит из модулей, внутри которых размещаются отдельные шаги обучения.")
line(doc, "Преподаватель может создавать новые модули, изменять их названия, удалять неактуальные элементы и дополнять структуру новыми шагами.")
line(doc, "Такой подход позволяет логически разделять учебный материал на тематические блоки и формировать последовательный образовательный маршрут для ученика.")
line(doc, "При необходимости структура курса может изменяться даже после первоначального создания — редактировать содержимое, менять порядок модулей, дополнять новыми разделами.")

divider(doc)

# ── ЭТАП 3 ────────────────────────────────────────────────────────────────
header(doc, "ЭТАП 3 — ПУБЛИКАЦИЯ")
line(doc, "Завершающим этапом является управление публикацией курса.")
line(doc, "Пока курс находится в стадии подготовки, он остаётся доступным только преподавателю.")
line(doc, "После завершения настройки структуры и наполнения содержимым курс может быть опубликован и станет доступен ученикам на платформе.")
line(doc, "Если требуется внести существенные изменения или временно ограничить доступ к материалам, преподаватель может снять курс с публикации.")
line(doc, "Такая возможность позволяет безопасно обновлять контент без влияния на качество обучения пользователей.")

divider(doc)

# ── ПАНЕЛЬ УПРАВЛЕНИЯ ─────────────────────────────────────────────────────
header(doc, "ЕДИНАЯ ПАНЕЛЬ УПРАВЛЕНИЯ")
line(doc, "Для удобства администрирования в интерфейсе реализована единая панель управления курсом.")
line(doc, "Все основные операции — создание, редактирование, настройка структуры и публикация — выполняются через последовательный и понятный пользовательский интерфейс.")
line(doc, "Благодаря этому преподавателю не требуется выполнять сложные действия или переходить между большим количеством страниц, что значительно упрощает процесс подготовки образовательных материалов.")

divider(doc)

