from docx import Document
from docx.shared import Pt, RGBColor, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

doc = Document()

# ── Поля ──────────────────────────────────────────────────────────────────
for section in doc.sections:
    section.top_margin    = Cm(2.0)
    section.bottom_margin = Cm(2.0)
    section.left_margin   = Cm(2.5)
    section.right_margin  = Cm(2.5)

RED  = RGBColor(0xDC, 0x26, 0x26)
DARK = RGBColor(0x0F, 0x17, 0x2A)
GRAY = RGBColor(0x55, 0x65, 0x81)

def header(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(7)
    p.paragraph_format.space_after  = Pt(2)
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(8)
    r.font.color.rgb = RED
    r.font.name = "Calibri"
    rPr = r._r.get_or_add_rPr()
    sp = OxmlElement("w:spacing"); sp.set(qn("w:val"), "60"); rPr.append(sp)

def line(doc, text, bold=False):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after  = Pt(3)
    r = p.add_run(text)
    r.bold = bold
    r.font.size = Pt(11)
    r.font.color.rgb = DARK
    r.font.name = "Calibri"

def divider(doc):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.space_after  = Pt(0)
    pPr = p._p.get_or_add_rPr() if False else p._p.get_or_add_pPr()
    pBdr = OxmlElement("w:pBdr")
    bot = OxmlElement("w:bottom")
    bot.set(qn("w:val"), "single"); bot.set(qn("w:sz"), "2")
    bot.set(qn("w:space"), "1");    bot.set(qn("w:color"), "CBD5E1")
    pBdr.append(bot); pPr.append(pBdr)

# ── Заголовок ──────────────────────────────────────────────────────────────
p = doc.add_paragraph()
p.alignment = WD_ALIGN_PARAGRAPH.CENTER
p.paragraph_format.space_after = Pt(4)
r = p.add_run("Речь · Модуль интерфейса · Gradus")
r.bold = True; r.font.size = Pt(11); r.font.color.rgb = RED; r.font.name = "Calibri"

divider(doc)

# ── ВСТУПЛЕНИЕ ────────────────────────────────────────────────────────────
header(doc, "ВСТУПЛЕНИЕ")
line(doc, "Уважаемая комиссия.")
line(doc, "Мои коллеги уже рассказали об архитектуре и серверной части платформы Gradus.")
line(doc, "Я отвечал за модуль пользовательского интерфейса — то, что пользователь видит на экране и с чем напрямую взаимодействует.")

divider(doc)

# ── ЧТО УМЕЕТ ИНТЕРФЕЙС ───────────────────────────────────────────────────
header(doc, "ЧТО УМЕЕТ ИНТЕРФЕЙС")
line(doc, "Платформа обслуживает три категории пользователей: студент, преподаватель и администратор.")
line(doc, "У каждого свой личный кабинет и свои права доступа.")
line(doc, "Интерфейс построен как одностраничное приложение — при первом заходе один раз скачивается код, и после этого все переходы происходят мгновенно, без перезагрузки страницы.")
line(doc, "Для платформы, где пользователь постоянно переключается между уроками и заданиями, это принципиально важно.")

divider(doc)

# ── ТЕХНОЛОГИИ ────────────────────────────────────────────────────────────
header(doc, "ТЕХНОЛОГИИ")
line(doc, "Основа интерфейса — React: интерфейс собирается из готовых компонентов, каждый написан один раз и используется в любом месте приложения.")
line(doc, "Код написан на TypeScript — он проверяет типы данных ещё до запуска приложения, как проверка орфографии в Word: выявляет проблемы до того, как они доходят до пользователя.")
line(doc, "За сборку отвечает Vite: удаляет неиспользуемый код, сжимает файлы и загружает только нужное.")
line(doc, "Стилизация — TailwindCSS: готовые классы прямо в разметке, без отдельных CSS-файлов. Адаптивность под любой экран задаётся там же — через префиксы sm, md, lg.")
line(doc, "Навигация — React Router: управляет переходами между страницами внутри браузера, без перезагрузки. Он же отвечает за защиту маршрутов по ролям — студент не попадёт на страницу администратора даже по прямой ссылке.")
line(doc, "Из дополнительных инструментов: Framer Motion для плавных анимаций переходов, Lucide для иконок, Prism для подсветки синтаксиса кода в уроках.")
line(doc, "Для визуальных эффектов на лендинге реализованы два собственных компонента: интерактивный глобус из бинарных цифр, где точки на карте мира изображают «активных студентов», и анимированная сеть частиц — фон hero-секции, где точки соединяются линиями и реагируют на движение мыши. Оба компонента написаны на Canvas 2D API браузера — без сторонних графических библиотек. Это даёт полный контроль над анимацией и не увеличивает вес страницы.")
line(doc, "Всего в проекте 22 экрана: кабинеты всех трёх ролей, прохождение курса, аналитика, настройки и служебные экраны.")

divider(doc)

# ── СТРУКТУРА КОДА ────────────────────────────────────────────────────────
header(doc, "СТРУКТУРА КОДА")
line(doc, "Код разделён на четыре слоя.")
line(doc, "Страницы — это то, что видит пользователь: 22 экрана для всех трёх ролей.")
