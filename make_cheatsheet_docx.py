    "Как отображается код в уроках, есть ли подсветка синтаксиса?",
    "Да, используется библиотека Prism. Она подсвечивает синтаксис для большинства популярных языков — Python, JavaScript, SQL и других — прямо в браузере, без серверной обработки."
